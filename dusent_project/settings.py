def _is_pg_connectable():
    # Never attempt local postgres connect during Vercel serverless builds
    if os.environ.get('VERCEL') == '1' or 'VERCEL_ENV' in os.environ:
        return False
    try:
        import psycopg2
        conn = psycopg2.connect(
            dbname=PG_NAME,
            user=PG_USER,
            password=PG_PASSWORD,
            host=PG_HOST,
            port=PG_PORT,
            connect_timeout=1
        )
        conn.close()
        return True
    except Exception:
        return False

import shutil

# On Vercel serverless environment, copy db.sqlite3 to /tmp so write operations succeed
is_vercel = os.environ.get('VERCEL') == '1' or 'VERCEL_ENV' in os.environ
source_sqlite = BASE_DIR / 'db.sqlite3'
writable_sqlite = Path('/tmp') / 'db.sqlite3'

if is_vercel and not DATABASE_URL:
    if source_sqlite.exists() and not writable_sqlite.exists():
        try:
            shutil.copyfile(source_sqlite, writable_sqlite)
        except Exception:
            pass
    active_sqlite_path = writable_sqlite if writable_sqlite.exists() else source_sqlite
else:
    active_sqlite_path = source_sqlite

if DATABASE_URL:
    try:
        import dj_database_url
        DATABASES = {
            'default': dj_database_url.config(
                default=DATABASE_URL,
                conn_max_age=600,
                ssl_require=True if ('neon' in DATABASE_URL or 'supabase' in DATABASE_URL) else False
            )
        }
    except Exception:
        DATABASES = {
            'default': {
                'ENGINE': 'django.db.backends.sqlite3',
                'NAME': active_sqlite_path,
            }
        }
elif _is_pg_connectable():
    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.postgresql',
            'NAME': PG_NAME,
            'USER': PG_USER,
            'PASSWORD': PG_PASSWORD,
            'HOST': PG_HOST,
            'PORT': PG_PORT,
        }
    }
else:
    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.sqlite3',
            'NAME': active_sqlite_path,
        }
    }


